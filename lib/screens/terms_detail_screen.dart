  List<Widget> _buildBodyWidgets(String body) {
    final headingPattern = RegExp(r'^제\d+조');
    final sections = <(String?, List<String>)>[];
    for (final line in body.trim().split('\n')) {
      if (headingPattern.hasMatch(line)) {
        sections.add((line, <String>[]));
      } else {
        if (sections.isEmpty) sections.add((null, <String>[]));
        sections.last.$2.add(line);
      }
    }

    final widgets = <Widget>[];
    for (var i = 0; i < sections.length; i++) {
      final (heading, lines) = sections[i];
      final rest = lines.join('\n').trim();
      if (heading != null) {
        widgets.add(
          Padding(
            padding: EdgeInsets.only(top: i == 0 ? 0 : 24, bottom: 8),
            child: Text(
              heading,
              style: const TextStyle(
                color: AppColors.ink,
                fontSize: 16,
                fontWeight: FontWeight.w800,
                height: 1.6,
              ),
            ),
          ),
        );
      }
      if (rest.isNotEmpty) {
        widgets.add(
          Text(
            rest,
            style: const TextStyle(
              color: AppColors.ink,
              fontSize: 13,
              height: 1.6,
              fontWeight: FontWeight.w400,
            ),
          ),
        );
      }
    }
    return widgets;
